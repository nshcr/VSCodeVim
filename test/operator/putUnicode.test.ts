suite('Unicode put boundaries', () => {
  for (const scenario of cases) {
    test(scenario.title, async () => {
      await setupWorkspace({ fileContent: [scenario.start], forceNewFile: true });
      const editor = vscode.window.activeTextEditor!;
      editor.selections = [new vscode.Selection(0, 0, 0, 0)];
      const modeHandler = (await getAndUpdateModeHandler())!;
      modeHandler.syncCursors();
      modeHandler.vimState.recordedState.registerName = '"';
      modeHandler.vimState.currentRegisterMode = RegisterMode.CharacterWise;
      Register.put(modeHandler.vimState, scenario.register);
      for (const text of scenario.keys) {
        await vscode.commands.executeCommand('type', { text });
        await new Promise<void>((resolve) => taskQueue.enqueueTask(async () => resolve()));
      }
      assertEqualLines([scenario.end]);
      assert.strictEqual(modeHandler.vimState.cursorStopPosition.character, scenario.cursor);
      assert.strictEqual(editor.selection.active.character, scenario.cursor);
      assert.strictEqual((await Register.get('"'))?.text, scenario.endRegister);
    });
  }
});
